'use strict'

const test = require('node:test')
const assert = require('node:assert/strict')
const { readFileSync } = require('node:fs')
const path = require('node:path')

const root = path.resolve(__dirname, '..')
const app = readFileSync(path.join(root, 'src', 'App.tsx'), 'utf8')
const css = readFileSync(path.join(root, 'src', 'styles', 'app.css'), 'utf8')
const main = readFileSync(path.join(root, 'desktop', 'main.cjs'), 'utf8')
const store = readFileSync(path.join(root, 'desktop', 'services', 'store.cjs'), 'utf8')

test('user messages copy text without restoring the draft or resources', () => {
  assert.match(app, /function copyUserMessage\(message: MessageItem\)/)
  assert.match(app, /window\.stable\.clipboard\.writeText\(message\.content\)/)
  assert.doesNotMatch(app, /copyUndoRef|undoCopiedDraft|restoredAttachments|复制这条消息到主输入框/)
  assert.match(app, /aria-label="复制这条消息"/)
  assert.match(main, /\{ kind, id: String\(item\.id\), \.\.\.metadata \}/)
  assert.match(main, /path: item\.path/)
  assert.match(store, /kind !== 'attachment' && item\.id/)
  assert.match(store, /kind === 'attachment' && item\.path/)
})

test('conversation links, generated files and uploaded attachments open a resizable in-window preview without a composer eye button', () => {
  const composer = app.slice(app.indexOf('<div className="composer">'), app.indexOf('{browserPanel?.open &&'))
  assert.doesNotMatch(composer, /<Eye|打开快捷预览|PreviewDialog/)
  assert.match(app, /<BrowserPanel/)
  assert.match(readFileSync(path.join(__dirname, '..', 'src', 'BrowserPanel.tsx'), 'utf8'), /role="separator"/)
  assert.match(readFileSync(path.join(__dirname, '..', 'src', 'BrowserPanel.tsx'), 'utf8'), /api\('show',\{tabId:tab!\.id,bounds:bounds\(\)\}\)/)
  assert.match(readFileSync(path.join(__dirname, '..', 'src', 'BrowserPanel.tsx'), 'utf8'), /window\.stable\.preview\.openFile/)
  assert.match(app, /function localArtifactPaths/)
  assert.match(app, /className="conversation-file-card"/)
  assert.match(app, /className="conversation-file-list artifact-links"/)
  assert.match(app, /className="conversation-file-list message-file-cards"/)
  assert.match(app, /className="markdown-preview-link"/)
  assert.doesNotMatch(app, /contextOpen|className="context-toggle"|className="context-panel"|data-context-open/)
  assert.match(css, /\.conversation-workspace\[data-preview-open="true"\]/)
  assert.match(css, /\.conversation-preview/)
  assert.match(css, /\.conversation-file-card:focus-visible/)
})

test('account menu exposes the global AGENTS.md editor and explains its future-task scope', () => {
  assert.match(app, /全局 Agent 对话提醒/)
  assert.match(app, /仅在之后启动的新任务中读取/)
  assert.match(app, /window\.stable\.settings\.globalInstructions\(\)/)
  assert.match(app, /window\.stable\.settings\.saveGlobalInstructions\(globalDraft\)/)
  assert.match(main, /readGlobalInstructionsFile\(app\.getPath\('userData'\)\)/)
  assert.match(main, /globalInstructions: readGlobalInstructions\(\)\.content/)
  assert.match(css, /\.global-instructions-settings/)
  assert.match(app, /Agent 对话记录/)
  assert.match(app, /className="account-content-popover"/)
})
