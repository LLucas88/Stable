'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { spawnSync } = require('node:child_process')
const { writeRollbackScript } = require('../desktop/services/upgrade-maintenance.cjs')
for (const mode of ['success','running','restore-failed']) test(`manual rollback ${mode} preserves installation and data in isolated paths`, {skip:process.platform!=='win32'}, t => {
  const root = fs.mkdtempSync(path.join(__dirname, '../.local/manual-rollback-'))
  t.after(()=>fs.rmSync(root,{recursive:true,force:true}))
  const install = path.join(root,"测试 ' Stable"), previous = install + '.__stable_previous_test', userData = path.join(root,'user-data')
  for (const dir of [install,previous,userData]) fs.mkdirSync(dir)
  fs.writeFileSync(path.join(install,'Stable.exe'),'new-program')
  fs.writeFileSync(path.join(previous,'Stable.exe'),'old-program')
  fs.writeFileSync(path.join(userData,'stable.db'),'history-sentinel')
  const script = path.join(root,'rollback.ps1'), harness = path.join(root,'run.ps1')
  writeRollbackScript(script,install,previous,mode==='restore-failed' ? path.join(root,'backup'):null,userData)
  fs.writeFileSync(harness, `$ErrorActionPreference = 'Stop'\nfunction Get-CimInstance { ${mode==='running' ? "return @{ Name = 'Stable.exe' }" : ''} }\nfunction Start-Process { return @{ ExitCode = 9 } }\n. '${script.replaceAll("'","''")}'\n`)
  const result = spawnSync('powershell.exe',['-NoLogo','-NoProfile','-NonInteractive','-ExecutionPolicy','Bypass','-File',harness],{encoding:'utf8',windowsHide:true,timeout:15000})
  assert.equal(result.status===0,mode==='success',result.stdout+result.stderr)
  assert.equal(fs.readFileSync(path.join(userData,'stable.db'),'utf8'),'history-sentinel')
  assert.equal(fs.readFileSync(path.join(install,'Stable.exe'),'utf8'),mode==='success'?'old-program':'new-program')
  if(mode==='success') {
    const failed = fs.readdirSync(root).find(n=>n.includes('.__stable_failed_rollback-'))
    assert.equal(fs.readFileSync(path.join(root,failed,'Stable.exe'),'utf8'),'new-program')
  } else assert.equal(fs.readFileSync(path.join(previous,'Stable.exe'),'utf8'),'old-program')
})
