'use strict'
const test = require('node:test'), assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path'), os = require('node:os')
const { StableStore } = require('../desktop/services/store.cjs')
const backup = require('../desktop/services/upgrade-backup.cjs')
const { legacyConversationContext } = require('../desktop/services/legacy-conversation.cjs')
function fixture(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'stable-upgrade-')), profile = path.join(root, 'user'); fs.mkdirSync(profile)
  t.after(() => fs.rmSync(root, { recursive: true, force: true }))
  const store = new StableStore(profile), id = store.activeConversationId()
  store.addMessage(id, 'user', 'ORIGINAL_REQUIREMENT: report for September')
  for (let i=0;i<210;i++) store.addMessage(id, 'assistant', 'history ' + i)
  store.saveRuntimeSession(id, { threadId: 'codex-old-thread', home: path.join(profile, 'codex', 'sessions', 'old'), version: '0.161.0' })
  fs.writeFileSync(path.join(profile, 'secrets.json'), '{"cloud.device-token":"encrypted-original"}')
  fs.mkdirSync(path.join(profile, 'workspace')); fs.writeFileSync(path.join(profile, 'workspace', 'report.html'), 'old-report')
  store.close()
  return { root, profile, id }
}
test('verified snapshot retains account, WAL history and files; rollback restores state and keeps newer files', t => {
  const { profile, id } = fixture(t), source = new StableStore(profile)
  source.addMessage(id, 'user', 'WAL_PENDING_MESSAGE')
  const saved = backup.prepareUpgrade(profile, '1.11.0')
  assert(saved); source.close()
  const manifest = backup.verifyBackup(saved, profile)
  assert(manifest.files.some(f => f.path === 'workspace' + path.sep + 'report.html'))
  const migrated = new StableStore(profile)
  assert.equal(migrated.db.prepare('SELECT count(*) n FROM messages').get().n, 212)
  migrated.addMessage(id, 'assistant', 'NEW_ENGINE_MESSAGE'); migrated.close()
  fs.writeFileSync(path.join(profile, 'secrets.json'), '{}')
  fs.writeFileSync(path.join(profile, 'workspace', 'report.html'), 'newer-report')
  backup.commitUpgrade(profile, '1.11.0', saved)
  assert.equal(backup.prepareUpgrade(profile, '1.11.0'), null)
  const recovery = backup.restoreBackup(saved, profile)
  assert(fs.existsSync(path.join(recovery, 'stable.db')))
  const restored = new StableStore(profile)
  assert.equal(restored.db.prepare('SELECT count(*) n FROM messages').get().n, 212); restored.close()
  assert.equal(fs.readFileSync(path.join(profile, 'workspace/report.html'), 'utf8'), 'newer-report')
  assert.match(fs.readFileSync(path.join(profile, 'secrets.json'), 'utf8'), /encrypted-original/)
})
test('failed migration rehearsal and corrupt backups never replace original state', t => {
  const { profile } = fixture(t), before = backup.digest(path.join(profile, 'stable.db'))
  assert.throws(() => backup.prepareUpgrade(profile, '1.11.0', { Store: class { constructor() { throw Error('unsupported schema') } } }), /unsupported schema/)
  assert.equal(backup.digest(path.join(profile, 'stable.db')), before)
  const saved = backup.prepareUpgrade(profile, '1.11.0')
  fs.writeFileSync(path.join(saved, 'profile/secrets.json'), 'corrupt')
  assert.throws(() => backup.restoreBackup(saved, profile), /校验失败/)
  assert.equal(backup.digest(path.join(profile, 'stable.db')), before)
})
test('model routing migration is allowed but deleting a historical message aborts the upgrade', t => {
  const { profile } = fixture(t), store = new StableStore(profile)
  store.db.exec("UPDATE conversations SET model_id=''"); store.close()
  assert(backup.prepareUpgrade(profile, '1.11.0'))
  class LosingStore extends StableStore { constructor(root) { super(root); this.db.exec('DELETE FROM messages WHERE seq=1') } }
  assert.throws(() => backup.prepareUpgrade(profile, '1.11.0', { Store: LosingStore }), /改变原历史/)
  const intact = new StableStore(profile)
  assert.equal(intact.db.prepare('SELECT count(*) n FROM messages').get().n, 211); intact.close()
})
test('interrupted data restore blocks startup until recovery completes, never creating an empty history', t => {
  const { profile } = fixture(t), saved = backup.prepareUpgrade(profile, '1.11.0')
  const rename = fs.renameSync
  fs.renameSync = (from, to) => { if (from === path.join(profile, 'secrets.json')) throw Error('simulated locked credentials'); return rename(from, to) }
  try { assert.throws(() => backup.restoreBackup(saved, profile), /locked credentials/) } finally { fs.renameSync = rename }
  assert.throws(() => backup.prepareUpgrade(profile, '1.11.0'), /恢复尚未完成/)
  backup.restoreBackup(saved, profile)
  const reopened = new StableStore(profile)
  assert.equal(reopened.db.prepare('SELECT count(*) n FROM messages').get().n, 211); reopened.close()
})
test('Codex continuation exposes full visible history beyond recent 200 messages and preserves old runtime mapping', t => {
  const { profile, id } = fixture(t), store = new StableStore(profile)
  const before = JSON.stringify(store.db.prepare('SELECT * FROM runtime_sessions').all())
  assert(!store.recentContext(id).some(row => row.content.includes('ORIGINAL_REQUIREMENT')))
  const context = legacyConversationContext(store, profile, id)
  assert.match(context.instruction, /ORIGINAL_REQUIREMENT/)
  const history = fs.readFileSync(path.join(context.readableRoot, 'visible-history.jsonl'), 'utf8').trim().split('\n')
  assert.equal(history.length, 211)
  assert.equal(JSON.stringify(store.db.prepare('SELECT * FROM runtime_sessions').all()), before)
  store.close()
})
