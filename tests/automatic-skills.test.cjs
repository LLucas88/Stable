'use strict'
const test = require('node:test'), assert = require('node:assert/strict')
const fs = require('node:fs'), os = require('node:os'), path = require('node:path')
const { StableStore } = require('../desktop/services/store.cjs')
const { automaticSkillCatalog, automaticSkillPrompt, selectedSkillReadRoots } = require('../desktop/services/skill-selection.cjs')
const { composeAgentPrompt } = require('../desktop/services/prompts.cjs')
const { assertWorkflowSkillInvocation } = require('../desktop/services/skill-invocation.cjs')
const { createNativeToolGuard } = require('../desktop/services/claude-native-tools.cjs')

test('automatic authorization is explicit, lazy, persistent and revoked by disabling or deleting a skill', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'stable-auto-skills-'))
  const directory = path.join(root, 'skills'), workspace = path.join(root, 'workspace')
  fs.mkdirSync(directory); fs.mkdirSync(workspace)
  fs.writeFileSync(path.join(directory, 'SKILL.md'), 'LAZY_SKILL_BODY')
  let store = new StableStore(root)
  t.after(() => { store.close(); fs.rmSync(root, { recursive:true, force:true }) })
  for (const id of ['auto','manual']) store.upsertSkill({id, name:id, path:directory, description:'创建 Excel 表格', content:'LAZY_SKILL_BODY'})
  assert.deepEqual(automaticSkillCatalog(store), [])
  store.setSetting('skillMarketMeta', { auto:{invocationMode:'auto'} })
  store.close(); store = new StableStore(root)
  const catalog = automaticSkillCatalog(store)
  assert.deepEqual(catalog.map(s => s.id), ['auto'])
  assert.equal(store.listSkills().find(s => s.id === 'auto').invocationMode, 'auto')
  assert.equal(catalog[0].content, undefined)
  const prompt = composeAgentPrompt({query:'制作 Excel', skills:[], automaticSkills:catalog})
  assert.match(prompt, /允许自动调用的 Skills/)
  assert.match(prompt, /创建 Excel 表格/)
  assert.match(prompt, /先用 Read 读取相应 SKILL.md/)
  assert.doesNotMatch(prompt, /LAZY_SKILL_BODY|请直接处理任务，不调用 Skill/)
  assert.match(prompt, /用户本次禁止使用技能时不调用/)
  const guard = createNativeToolGuard({workspace, writableRoots:[workspace], readableRoots:selectedSkillReadRoots(catalog), sandboxMode:'workspace-write'})
  assert.equal((await guard.canUseTool('Read', {file_path:path.join(directory,'SKILL.md')}, {})).behavior, 'allow')
  assert.equal((await guard.canUseTool('Write', {file_path:path.join(directory,'new.md'),content:'bad'}, {})).behavior, 'deny')
  store.setSkillEnabled('auto', false)
  assert.deepEqual(automaticSkillCatalog(store), [])
  store.setSkillEnabled('auto', true)
  fs.unlinkSync(path.join(directory,'SKILL.md'))
  assert.deepEqual(automaticSkillCatalog(store), [])
  assert.equal(automaticSkillPrompt([]), '')
})

test('automatic workflow nodes only accept specifically authorized skills', () => {
  const graph = {nodes:[{type:'skill',resourceId:'auto'},{type:'ai'}]}
  assert.doesNotThrow(() => assertWorkflowSkillInvocation(graph,false,[{id:'auto'}]))
  assert.throws(() => assertWorkflowSkillInvocation(graph,false,[{id:'other'}]), /手动/)
  assert.doesNotThrow(() => assertWorkflowSkillInvocation(graph,true,[]))
})
