const test = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { StableStore } = require('../desktop/services/store.cjs')
function setup(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'stable-answer-tools-'))
  let store = new StableStore(root)
  t.after(() => { store.close(); fs.rmSync(root, { recursive: true, force: true }) })
  return { root, get store() { return store }, restart() { store.close(); store = new StableStore(root) } }
}
test('fork copies all history through the chosen answer, retains context, and isolates runtime and approvals', t => {
  const f = setup(t), s = f.store, source = s.activeConversationId()
  const project = s.registerProject('测试项目', f.root)
  s.bindProject(source, project, f.root)
  s.updateConversationContext(source, 'high', ['data-1'])
  s.updateConversationPermission(source, 'request')
  s.setConversationNetwork(source, false)
  s.setSetting('conversation-skills:' + source, ['skill-1'])
  s.grantConversationApproval(source, 'a'.repeat(64), 'source only')
  for (let i = 0; i < 202; i++) s.addMessage(source, i % 2 ? 'assistant' : 'user', 'history ' + i)
  const picked = s.addMessage(source, 'assistant', '目标回答 🦀', [{ kind: 'tool', status: 'running', clarification: { status: 'waiting' } }], [{ name: 'sample.csv', path: path.join(f.root, 'sample.csv') }], { status: 'pending', title: '待审批任务' })
  s.setChapter(source, picked.id, '目标章节')
  s.addMessage(source, 'user', '后续内容不能出现在分支')
  const original = s.db.prepare('SELECT * FROM messages WHERE conversation_id=? ORDER BY seq').all(source)
  const fork = s.forkAnswer(source, picked.id)
  const cloned = s.db.prepare('SELECT * FROM messages WHERE conversation_id=? ORDER BY seq').all(fork)
  assert.equal(s.activeConversationId(), fork)
  assert.equal(cloned.length, 203)
  assert.deepEqual(cloned.map(row => [row.content, row.created_at]), original.slice(0, -1).map(row => [row.content, row.created_at]))
  assert.ok(cloned.every(row => !original.some(item => item.id === row.id)))
  assert.deepEqual(s.db.prepare('SELECT * FROM messages WHERE conversation_id=? ORDER BY seq').all(source), original)
  assert.equal(s.conversationContext(fork).projectId, project)
  assert.equal(s.conversation(fork).capability, 'high')
  assert.equal(s.conversation(fork).permissionMode, 'request')
  assert.equal(s.permissionContext(fork).networkAccess, false)
  assert.deepEqual(s.getSetting('conversation-skills:' + fork), ['skill-1'])
  assert.equal(s.hasConversationApproval(fork, 'a'.repeat(64)), false)
  assert.equal(s.db.prepare('SELECT count(*) n FROM runtime_sessions WHERE conversation_id=?').get(fork).n, 0)
  assert.equal(cloned.at(-1).automation_json, null)
  assert.equal(JSON.parse(cloned.at(-1).trace_json)[0].status, 'cancelled')
  assert.equal(JSON.parse(cloned.at(-1).trace_json)[0].clarification, undefined)
  assert.equal(cloned.at(-1).attachments_json, original.at(-2).attachments_json)
  f.restart()
  assert.equal(f.store.chapters(fork)[0].messageId, cloned.at(-1).id)
  f.store.setChapter(fork, cloned.at(-1).id, '改分支章节')
  assert.equal(f.store.chapters(source)[0].title, '目标章节')
})
test('chapters persist, order by message position, validate ownership, rename and unpin without changing answers', t => {
  const f = setup(t), s = f.store, id = s.activeConversationId()
  const user = s.addMessage(id, 'user', '提问'), a = s.addMessage(id, 'assistant', 'A'), b = s.addMessage(id, 'assistant', 'B')
  s.setChapter(id, b.id, '第二章'); s.setChapter(id, a.id, '第一章')
  assert.deepEqual(s.chapters(id).map(row => row.title), ['第一章', '第二章'])
  s.setChapter(id, a.id, ' 重命名 '); f.restart()
  assert.equal(f.store.chapters(id)[0].title, '重命名')
  const other = f.store.createConversation()
  assert.throws(() => f.store.setChapter(other, a.id, '错误对话'), /已保存/)
  assert.throws(() => f.store.setChapter(id, user.id, '用户消息'), /已保存/)
  for (const title of ['', ' ', 'a'.repeat(81), {}, undefined]) assert.throws(() => f.store.setChapter(id, a.id, title), /名称/)
  f.store.setChapter(id, a.id, null)
  assert.equal(f.store.chapters(id).length, 1)
  assert.equal(f.store.listMessages(id).find(row => row.id === a.id).content, 'A')
  f.store.clearMessages(id)
  assert.equal(f.store.db.prepare('SELECT count(*) n FROM answer_chapters').get().n, 0)
})
test('invalid fork and failed transaction do not leave a new conversation or change selection', t => {
  const f = setup(t), s = f.store, id = s.activeConversationId()
  const user = s.addMessage(id, 'user', '提问'), reply = s.addMessage(id, 'assistant', '回答')
  assert.throws(() => s.forkAnswer(id, user.id), /已保存/)
  assert.throws(() => s.forkAnswer('missing', reply.id), /来源/)
  s.db.exec(`CREATE TRIGGER prevent_fork BEFORE INSERT ON messages WHEN NEW.conversation_id<>'${id}' BEGIN SELECT RAISE(ABORT,'fixture failure'); END;`)
  assert.throws(() => s.forkAnswer(id, reply.id), /fixture failure/)
  assert.equal(s.activeConversationId(), id)
  assert.equal(s.listConversations().length, 1)
})
