'use strict'
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict')
const { spawnSync } = require('node:child_process')
const { DatabaseSync } = require('node:sqlite')
const repo = path.resolve(__dirname, '..')
const directory = path.resolve(process.argv[2])
const root = fs.mkdtempSync(path.join(repo, '.local/portable-packaged-'))
const profile = path.join(root, 'profile'), config = path.join(root, 'fixture.json'), receiver = path.join(root, 'receiver.exe')
fs.writeFileSync(config, JSON.stringify({ version: 1, profile: { providerId: 'packaged-test', displayName: '配置包测试', baseURL: 'https://example.com/v1', model: 'test-model' }, apiKey: 'fixture-packaged-key' }))
const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE; delete env.STABLE_CLOUD_ENABLED
function run(exe, args, extra = {}) {
  const result = spawnSync(exe, args, { env: { ...env, ...extra }, windowsHide: true, encoding: 'utf8', timeout: 30000 })
  assert.equal(result.status, 0, result.stdout + result.stderr)
}
run(path.join(repo, 'deliverables/model-setup-20260927/Stable-Config-Builder.exe'), ['--build', config, receiver])
run(receiver, ['--check-installation', path.join(directory, 'Stable.exe')])
run(receiver, ['--stage-only', profile])
const probe = path.join(root, 'probe.json')
run(path.join(directory, 'Stable.exe'), [], { STABLE_QA_USER_DATA: profile, STABLE_STARTUP_PROBE: probe })
assert.equal(JSON.parse(fs.readFileSync(probe)).status, 'ready')
const result = JSON.parse(fs.readFileSync(path.join(profile, 'model-setup.status.json')))
assert.equal(result.status, 'loaded')
assert.ok(!fs.readFileSync(path.join(profile, 'secrets.json'), 'utf8').includes('fixture-packaged-key'))
assert.equal(fs.existsSync(path.join(profile, 'model-setup.pending.json')), false)
const db = new DatabaseSync(path.join(profile, 'stable.db'), { readOnly: true })
const catalog = JSON.parse(db.prepare("SELECT value_json FROM settings WHERE key='modelCatalog'").get().value_json)
assert.equal(catalog.defaultModelId, result.modelId)
assert.ok(catalog.items.some(m => m.id === result.modelId && m.model === 'test-model'))
db.close()
console.log('PORTABLE_SETUP_PACKAGED_PASS: EXE generation, recipient encryption, real packaged startup, automatic import, selected model, no plaintext stored')
