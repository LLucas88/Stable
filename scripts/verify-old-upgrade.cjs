'use strict'
const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict')
const { StableStore } = require('../desktop/services/store.cjs')
const backup = require('../desktop/services/upgrade-backup.cjs')
const { legacyConversationContext } = require('../desktop/services/legacy-conversation.cjs')
const oldRoot = path.resolve(process.argv[2]), oldPackage = require(path.join(oldRoot, 'package.json'))
const OldStore = require(path.join(oldRoot, 'desktop/services/store.cjs')).StableStore
const root = fs.mkdtempSync(path.resolve(__dirname, '../.local/old-upgrade-')), profile = path.join(root, 'profile')
const old = new OldStore(profile), id = old.activeConversationId()
old.renameConversation(id, '旧版中文报告会话')
old.addMessage(id, 'user', '最初要求：九月经营报告，不得改变原数据。')
for (let i=0;i<210;i++) old.addMessage(id, 'assistant', '历史记录 ' + i)
old.setSetting('cloudDeviceId', 'legacy-device-id')
old.saveRuntimeSession(id, { threadId: 'old-codex-thread', home: path.join(profile, 'codex/sessions/old'), model: 'legacy-model', version: '0.161.0' })
const before = JSON.stringify(old.db.prepare('SELECT * FROM messages ORDER BY seq').all()); old.close()
fs.writeFileSync(path.join(profile, 'secrets.json'), '{"cloud:device-token":"opaque-encrypted-value"}')
const saved = backup.prepareUpgrade(profile, '1.11.0')
const current = new StableStore(profile)
assert.equal(JSON.stringify(current.db.prepare('SELECT * FROM messages ORDER BY seq').all()), before)
assert.equal(current.getSetting('cloudDeviceId'), 'legacy-device-id')
const context = legacyConversationContext(current, profile, id)
assert.match(context.instruction, /最初要求/)
current.addMessage(id, 'user', '升级后继续调整图表')
current.close(); backup.restoreBackup(saved, profile)
const restored = new OldStore(profile)
assert.equal(JSON.stringify(restored.db.prepare('SELECT * FROM messages ORDER BY seq').all()), before)
restored.close()
const report = { oldVersion: oldPackage.version, oldDescription: oldPackage.description, oldSource: oldRoot, preservedMessages: 211, oldDeviceIdentityRetained: true, legacyContextReadable: true, oldEngineReopensRolledBackDatabase: true, backup: saved }
fs.writeFileSync(path.join(root, 'result.json'), JSON.stringify(report, null, 2)); console.log(JSON.stringify({ ...report, evidence: path.join(root, 'result.json') }, null, 2))
